import { chromium } from 'playwright-core';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createPreview } from '../scripts/live-preview/server.mjs';
import { scanAnnotations } from '../scripts/check-annotations.mjs';

import { test } from 'node:test';

test('live editor interactions and AI handoff on all three HTML templates', { skip: !process.env.CHROME_PATH }, async () => {
const root = path.resolve('tmp/preview-browser-' + Date.now());
await mkdir(root, { recursive: true });
await cp('templates', path.join(root, 'templates'), { recursive: true });
await cp('assets', path.join(root, 'assets'), { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 }, locale: 'zh-CN' });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
let preview;
const stop = async () => { if (preview) { preview.server.closeAllConnections(); await new Promise((resolve) => preview.server.close(resolve)); preview = null; } };
const waitFrame = async () => { await page.waitForFunction(() => !!document.querySelector('iframe')?.contentDocument?.querySelector('.page,.resume-page')); await page.waitForTimeout(400); return page.frames().find((frame) => frame.parentFrame()); };
const select = async (frame, selector) => { await frame.locator(selector).first().click(); await page.locator('#annotation-input').waitFor({ state: 'visible' }); };
const assertQuotedFontField = async (frame) => {
  const expected = await frame.locator('h1').first().evaluate((element) => getComputedStyle(element).fontFamily);
  assert.ok(expected.includes('"'), 'Exercise a font list containing quoted family names');
  const input = page.locator('[data-style="font-family"]');
  assert.equal(await input.inputValue(), expected);
  assert.deepEqual(await input.evaluate((element) => element.getAttributeNames().sort()), ['class', 'data-style', 'value']);
};
const save = async () => { await page.locator('#btn-save').click(); await page.locator('#modal-confirm').click(); await page.waitForFunction(() => document.querySelector('#modal-message').textContent.includes('保存')); await page.locator('#modal-overlay').click({position:{x:10,y:10}}); await page.waitForTimeout(400); };
try {
  const input = 'templates/internship-employment/standard-one-page/index.html';
  preview = await createPreview({ root, input, port: 0, timeout: 0 });
  await page.goto(preview.url);
  let frame = await waitFrame();
  assert.equal(await frame.locator('.profile-photo').evaluate((image) => image.complete && image.naturalWidth > 0), true);
  const baseline = await readFile(path.join(root, input), 'utf8');
  await select(frame, 'h1');
  await assertQuotedFontField(frame);
  await page.locator('.prop-edit-content').fill('Browser verified name');
  await page.locator('.prop-edit-content').dispatchEvent('change');
  await page.waitForFunction(() => document.querySelector('#btn-undo').textContent.includes('(1)'));
  assert.equal(await readFile(path.join(root, input), 'utf8'), baseline);
  await frame.locator('h1').filter({hasText:'Browser verified name'}).waitFor();
  assert.equal(await frame.locator('h1').textContent(), 'Browser verified name');
  await page.locator('#btn-undo').click();
  await page.waitForTimeout(500);
  frame = await waitFrame();
  assert.equal(await frame.locator('h1').textContent(), 'Alex Chen');
  await select(frame, 'h1');
  const color = page.locator('[data-style="color"]');
  await color.fill('#2244aa'); await color.dispatchEvent('change');
  await page.waitForFunction(() => document.querySelector('#btn-undo').textContent.includes('(1)'));
  await frame.locator('h1').click();
  await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(250);
  assert.equal(await frame.locator('h1').evaluate((el) => el.style.left), '1px');
  await page.locator('#annotation-text').fill('把姓名改成“预览验证”');
  await page.locator('#btn-add-annotation').click();
  await page.waitForFunction(() => document.querySelector('#annotations').textContent.includes('预览验证'));
  await save();
  assert.equal((await scanAnnotations(path.join(root, input)))[0].annotation, '把姓名改成“预览验证”');
  assert.ok((await readFile(path.join(root, input), 'utf8')).includes('color: #2244aa'));
  await page.screenshot({ path: path.join(root, 'standard-preview.png'), fullPage: true });
  // AI handoff on the disposable copy: locate the annotated element, make the
  // requested edit, clear markers, then let polling show the new source.
  const saved = await readFile(path.join(root, input), 'utf8');
  await writeFile(path.join(root, input), saved.replace('Alex Chen</h1>', '预览验证</h1>').replace(/ data-edit-target="true"/g, '').replace(/ data-edit-annotation="[^"]*"/g, ''));
  await page.waitForTimeout(2800);
  frame = await waitFrame();
  assert.equal(await frame.locator('h1').textContent(), '预览验证');
  assert.equal((await scanAnnotations(path.join(root, input))).length, 0);
  const css = path.join(root, path.dirname(input), 'styles.css');
  await writeFile(css, (await readFile(css, 'utf8')) + '\n.eyebrow { color: rgb(170, 34, 51) !important; }\n');
  await page.waitForTimeout(2800); frame = await waitFrame();
  assert.equal(await frame.locator('.eyebrow').evaluate((element) => getComputedStyle(element).color), 'rgb(170, 34, 51)');
  console.log('standard: assets, leaf edit, undo, style, nudge, annotations, save, AI handoff and live refresh passed');
  await stop();
  const dense = 'templates/internship-employment/dense-two-page/index.html';
  preview = await createPreview({ root, input: dense, port: 0, timeout: 0 });
  await page.goto(preview.url); frame = await waitFrame();
  assert.equal(await page.locator('.slide-item').count(), 2);
  await select(frame, 'h1');
  await assertQuotedFontField(frame);
  const title = frame.locator('h1');
  const box = await title.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 12, box.y + box.height / 2 + 8, { steps: 6 }); await page.mouse.up();
  await page.waitForTimeout(300);
  assert.ok(parseFloat(await title.evaluate((element) => element.style.left)) > 10);
  await page.locator('#nav-next').click(); frame = await waitFrame();
  assert.equal(await frame.locator('.resume-page').nth(0).isVisible(), false);
  assert.equal(await frame.locator('.resume-page').nth(1).isVisible(), true);
  await select(frame, '.page-two-section h3');
  await page.locator('#annotation-text').fill('缩短这一段'); await page.locator('#btn-add-annotation').click();
  await page.waitForTimeout(200); await save();
  assert.equal((await scanAnnotations(path.join(root, dense)))[0].page, 2);
  await page.screenshot({ path: path.join(root, 'dense-preview.png'), fullPage: true });
  console.log('dense: page navigation, drag, cross-page staging, page-2 annotation and save passed');
  await stop();
  const research = 'templates/research-application/research-classic/index.html';
  preview = await createPreview({ root, input: research, port: 0, timeout: 0 });
  await page.goto(preview.url); frame = await waitFrame();
  await select(frame, 'h1');
  await assertQuotedFontField(frame);
  await page.locator('[data-style="font-size"]').fill('32px'); await page.locator('[data-style="font-size"]').dispatchEvent('change');
  await page.waitForTimeout(200); await save();
  await page.screenshot({ path: path.join(root, 'research-preview.png'), fullPage: true });
  console.log('research: long-page preview, typography edit and save passed');
  assert.deepEqual(errors, []);
  console.log('No browser JavaScript errors. Outputs: ' + root);
} catch (error) { await page.screenshot({ path: path.join(root, 'failure.png') }).catch(() => {}); throw error; } finally { await stop(); await browser.close(); }

});
